let currentLanguage = "en";
let activeProject = null;
let activeImageIndex = 0;

const dialog = document.querySelector("#projectDialog");
const dialogTitle = document.querySelector("#dialogTitle");
const dialogCategory = document.querySelector("#dialogCategory");
const dialogOverviewLabel = document.querySelector("#dialogOverviewLabel");
const dialogDescription = document.querySelector("#dialogDescription");
const dialogChallengeLabel = document.querySelector("#dialogChallengeLabel");
const dialogChallenge = document.querySelector("#dialogChallenge");
const dialogContributionLabel = document.querySelector("#dialogContributionLabel");
const dialogContribution = document.querySelector("#dialogContribution");
const dialogOutcomeLabel = document.querySelector("#dialogOutcomeLabel");
const dialogOutcome = document.querySelector("#dialogOutcome");
const dialogFacts = document.querySelector("#dialogFacts");
const dialogImage = document.querySelector("#dialogImage");
const imageCount = document.querySelector("#imageCount");
const previousButton = document.querySelector(".gallery-control--previous");
const nextButton = document.querySelector(".gallery-control--next");

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = language === "zh"
    ? "林婧柔 Jinelle — 体验与传播设计师"
    : "Jinelle Lin — Experience & Communication Designer";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[language][key];
    if (!value) return;
    if (key === "aboutTitle") {
      element.innerHTML = value;
    } else {
      element.textContent = value;
    }
  });

  document.querySelectorAll(".language-option").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  document.querySelectorAll("[data-project]").forEach((button) => {
    const project = projects[button.dataset.project];
    if (!project) return;
    const action = language === "zh" ? "打开项目" : "Open project";
    button.setAttribute("aria-label", `${action}: ${project.title[language]}`);
  });

  try {
    localStorage.setItem("jinelle-portfolio-language", language);
  } catch (error) {
    // The site still works when storage is unavailable.
  }

  if (activeProject) updateDialog();
}

function updateDialog() {
  const project = projects[activeProject];
  if (!project) return;
  const imageName = project.images[activeImageIndex];
  dialogTitle.textContent = project.title[currentLanguage];
  dialogCategory.textContent = project.category[currentLanguage];
  dialogOverviewLabel.textContent = translations[currentLanguage].projectOverview;
  dialogDescription.textContent = project.description[currentLanguage];
  dialogChallengeLabel.textContent = translations[currentLanguage].projectChallenge;
  dialogChallenge.textContent = project.challenge[currentLanguage];
  dialogContributionLabel.textContent = translations[currentLanguage].projectContribution;
  dialogContribution.replaceChildren();
  project.contribution[currentLanguage].forEach((contribution) => {
    const item = document.createElement("li");
    item.textContent = contribution;
    dialogContribution.append(item);
  });
  dialogOutcomeLabel.textContent = translations[currentLanguage].projectOutcome;
  dialogOutcome.textContent = project.outcome[currentLanguage];
  dialogFacts.replaceChildren();
  const facts = project.facts || [];
  dialogFacts.hidden = facts.length === 0;
  facts.forEach((fact) => {
    const item = document.createElement("div");
    item.className = "dialog-fact";
    const value = document.createElement("strong");
    value.textContent = fact.value;
    const label = document.createElement("span");
    label.textContent = fact[currentLanguage];
    item.append(value, label);
    dialogFacts.append(item);
  });
  dialogImage.src = `assets/images/${imageName}`;
  dialogImage.alt = `${project.title[currentLanguage]} — ${activeImageIndex + 1}`;
  imageCount.textContent = `${activeImageIndex + 1} / ${project.images.length}`;
  const singleImage = project.images.length === 1;
  previousButton.hidden = singleImage;
  nextButton.hidden = singleImage;
}

function openProject(projectKey) {
  if (!projects[projectKey]) return;
  activeProject = projectKey;
  activeImageIndex = 0;
  updateDialog();
  dialog.showModal();
  document.body.classList.add("dialog-open");
}

function changeImage(direction) {
  const project = projects[activeProject];
  if (!project || project.images.length < 2) return;
  activeImageIndex = (activeImageIndex + direction + project.images.length) % project.images.length;
  updateDialog();
}

document.querySelectorAll(".language-option").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

document.querySelectorAll("[data-project]").forEach((button) => {
  button.addEventListener("click", () => openProject(button.dataset.project));
});

document.querySelector(".dialog-close").addEventListener("click", () => dialog.close());
previousButton.addEventListener("click", () => changeImage(-1));
nextButton.addEventListener("click", () => changeImage(1));

dialog.addEventListener("click", (event) => {
  if (event.target === dialog) dialog.close();
});

dialog.addEventListener("close", () => {
  document.body.classList.remove("dialog-open");
  activeProject = null;
});

document.addEventListener("keydown", (event) => {
  if (!dialog.open) return;
  if (event.key === "ArrowLeft") changeImage(-1);
  if (event.key === "ArrowRight") changeImage(1);
});

const revealElements = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  revealElements.forEach((element) => element.classList.add("will-reveal"));
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.12 });
  revealElements.forEach((element) => observer.observe(element));
}

